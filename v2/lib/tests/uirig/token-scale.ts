import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

export interface CombinedTokenResult {
  combinedCss: string;
  darkRgbValues: Set<string>;
}

export function hexToRgbString(hex: string): string | null {
  const cleaned = hex.trim().replace(/^#/, '');
  if (!/^[0-9a-fA-F]{3}$|^[0-9a-fA-F]{6}$/.test(cleaned)) {
    return null;
  }
  const full =
    cleaned.length === 3
      ? cleaned
          .split('')
          .map((ch) => ch + ch)
          .join('')
      : cleaned;
  const r = Number.parseInt(full.slice(0, 2), 16);
  const g = Number.parseInt(full.slice(2, 4), 16);
  const b = Number.parseInt(full.slice(4, 6), 16);
  return `rgb(${r}, ${g}, ${b})`;
}

export function extractDarkRgbTokens(darkCss: string): Set<string> {
  const values = new Set<string>();
  const hexMatches = darkCss.matchAll(/#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b/g);
  for (const match of hexMatches) {
    const rgb = hexToRgbString(match[0]);
    if (rgb) {
      values.add(rgb);
    }
  }
  return values;
}

export function buildCombinedTokenCss(lightCss: string, darkCss: string): CombinedTokenResult {
  const combinedCss = [
    '/* Auto-generated by tests/uirig/token-scale.ts for @rlevin/uirig */',
    lightCss.trim(),
    darkCss.trim(),
    '',
  ].join('\n\n');

  return {
    combinedCss,
    darkRgbValues: extractDarkRgbTokens(darkCss),
  };
}

export function writeCombinedTokenScale(
  lightTokensPath: string,
  darkTokensPath: string,
  outputPath: string
): CombinedTokenResult {
  const lightCss = readFileSync(lightTokensPath, 'utf8');
  const darkCss = readFileSync(darkTokensPath, 'utf8');
  const result = buildCombinedTokenCss(lightCss, darkCss);
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, result.combinedCss, 'utf8');
  return result;
}
