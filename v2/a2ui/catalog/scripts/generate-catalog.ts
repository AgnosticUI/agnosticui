type A2uiPropKind = 'dynamicString' | 'dynamicBoolean' | 'dynamicNumber' | 'enum' | 'literal' | 'stringArray' | 'numberArray';

interface A2uiPropInfo {
  name: string;
  kind: A2uiPropKind;
  zodExpr: string;
  tsType: string;
}

function toKebab(name: string): string {
  return name.replace(/([A-Z])/g, (_, c) => '-' + c.toLowerCase()).replace(/^-/, '');
}

function quoteName(name: string): string {
  return /[^a-zA-Z0-9_$]/.test(name) ? `'${name}'` : name;
}

function isFunctionSymbol(sym: MorphSymbol): boolean {
  const decl = sym.getValueDeclaration();
  if (!decl) return false;
  return decl.getType().getNonNullableType().getCallSignatures().length > 0;
}

function mapA2uiType(propName: string, type: Type): Omit<A2uiPropInfo, 'name'> | null {
  const t = type.getNonNullableType();

  if (t.isBoolean()) {
    return {
      kind: 'dynamicBoolean',
      tsType: 'boolean',
      zodExpr: `DynamicBooleanSchema.describe('REF:#/$defs/DynamicBoolean|Boolean property ${propName}.')`,
    };
  }
  if (t.isString()) {
    return {
      kind: 'dynamicString',
      tsType: 'string',
      zodExpr: `DynamicStringSchema.describe('REF:#/$defs/DynamicString|String property ${propName}.')`,
    };
  }
  if (t.isNumber()) {
    return {
      kind: 'dynamicNumber',
      tsType: 'number',
      zodExpr: `DynamicNumberSchema.describe('REF:#/$defs/DynamicNumber|Numeric property ${propName}.')`,
    };
  }

  if (t.isArray()) {
    const el = t.getArrayElementType();
    if (!el) return null;
    const elNonNull = el.getNonNullableType();
    if (elNonNull.isString()) {
      return { kind: 'stringArray', tsType: 'string[]', zodExpr: 'z.array(z.string())' };
    }
    if (elNonNull.isNumber()) {
      return { kind: 'numberArray', tsType: 'number[]', zodExpr: 'z.array(z.number())' };
    }
    return null;
  }

  if (t.isUnion()) {
    const members = t.getUnionTypes().filter(
      (m) =>
        !m.isUndefined() &&
        !m.isNull() &&
        !m.isBoolean() &&
        !m.isBooleanLiteral() &&
        !(m.isStringLiteral() && m.getLiteralValue() === ''),
    );
    if (members.length === 0) return null;
    if (members.length === 1) return mapA2uiType(propName, members[0]);

    if (members.every((m) => m.isStringLiteral())) {
      const values = members.map((m) => m.getLiteralValue() as string);
      return {
        kind: 'enum',
        tsType: values.map((v) => `'${v}'`).join(' | '),
        zodExpr: `z.enum([${values.map((v) => `'${v}'`).join(', ')}])`,
      };
    }

    if (members.some((m) => m.isString() || m.isStringLiteral())) {
      return {
        kind: 'dynamicString',
        tsType: 'string',
        zodExpr: `DynamicStringSchema.describe('REF:#/$defs/DynamicString|String property ${propName}.')`,
      };
    }
    return null;
  }

  if (t.isStringLiteral()) {
    const v = t.getLiteralValue() as string;
    if (v === '') return null;
    return { kind: 'literal', tsType: `'${v}'`, zodExpr: `z.literal('${v}')` };
  }

  return null;
}

function extractProps(componentName: string, iface: InterfaceDeclaration): { props: A2uiPropInfo[]; hasActions: boolean } {
  const sdui = `Ag${componentName}`;
  const manualOmit = new Set(omitConfig[sdui] ?? []);
  const overrides = (typeOverrides as Record<string, Record<string, { tsType: string; zodExpr: string }>>)[sdui] ?? {};
  const props: A2uiPropInfo[] = [];
  let hasActions = false;

  for (const sym of iface.getType().getProperties()) {
    const propName = sym.getName();
    if (manualOmit.has(propName)) continue;
    const decl = sym.getValueDeclaration();
    if (!decl) continue;

    if (isFunctionSymbol(sym)) {
      if (actionAliasMap[propName]) hasActions = true;
      continue;
    }

    if (overrides[propName]) {
      const ov = overrides[propName];
      if (ov.zodExpr === 'z.string()') {
        props.push({
          name: propName,
          kind: 'dynamicString',
          tsType: 'string',
          zodExpr: `DynamicStringSchema.describe('REF:#/$defs/DynamicString|String property ${propName}.')`,
        });
      } else {
        props.push({ name: propName, kind: 'enum', tsType: ov.tsType, zodExpr: ov.zodExpr });
      }
      continue;
    }

    const mapped = mapA2uiType(propName, decl.getType());
    if (mapped) {
      props.push({ name: propName, ...mapped });
    }

    if (rendererSlotConfig[sdui] === 'label-child' && !props.some((p) => p.name === 'label')) {
      props.unshift({
        name: 'label',
        kind: 'dynamicString',
        tsType: 'string',
        zodExpr: `DynamicStringSchema.describe('REF:#/$defs/DynamicString|Text label displayed inside ${sdui}.')`,
      });
    }

    if (sdui === 'AgSelect' && !props.some((p) => p.name === 'value')) {
      props.push({
        name: 'value',
        kind: 'dynamicString',
        tsType: 'string',
        zodExpr: `DynamicStringSchema.describe('REF:#/$defs/DynamicString|Selected option value for ${sdui}.')`,
      });
    }
  }

  if (rendererSlotConfig[sdui] === 'label-child' && !props.some((p) => p.name === 'label')) {
    props.unshift({
      name: 'label',
      kind: 'dynamicString',
      tsType: 'string',
      zodExpr: `DynamicStringSchema.describe('REF:#/$defs/DynamicString|Text label displayed inside ${sdui}.')`,
    });
  }

  return { props, hasActions };
}

function generateWrapperFile(
  componentName: string,
  props: A2uiPropInfo[],
  slotType: RendererSlot,
  hasActions: boolean,
): string {
  const sdui = `Ag${componentName}`;
  const slug = toKebab(componentName);
  const tag = `ag-${slug}`;
  const wrapperTag = `ag-a2ui-${slug}`;
  const elementClass = `AgA2ui${componentName}Element`;
  const noUndef = new Set(noUndefinedProps[sdui] ?? []);
  const twoWay = TWO_WAY_BINDINGS[sdui];
  const customAction = CUSTOM_ACTION_EVENTS[sdui];

  const needsDynamicString = props.some((p) => p.kind === 'dynamicString');
  const needsDynamicBoolean = props.some((p) => p.kind === 'dynamicBoolean');
  const needsDynamicNumber = props.some((p) => p.kind === 'dynamicNumber');
  const needsChildList = slotType === 'children' || slotType === 'label-child';

  const coreImports = ['A2uiLitElement'];
  if (hasActions) coreImports.push('ActionSchema');
  if (needsChildList) coreImports.push('ChildListSchema');
  if (needsDynamicBoolean) coreImports.push('DynamicBooleanSchema');
  if (needsDynamicNumber) coreImports.push('DynamicNumberSchema');
  if (needsDynamicString) coreImports.push('DynamicStringSchema');

  const schemaLines: string[] = [];
  if (needsChildList) {
    schemaLines.push(
      `    children: ChildListSchema.describe('REF:#/$defs/ChildList|Child component IDs rendered inside ${sdui}.').optional(),`,
    );
  }
  for (const p of props) {
    schemaLines.push(`    ${quoteName(p.name)}: ${p.zodExpr}.optional(),`);
  }
  if (sdui === 'AgTimeline') {
    schemaLines.push(
      `    items: z.array(z.object({ start: z.string().optional(), marker: z.string().optional(), end: z.string().optional(), markerAriaLabel: z.string().optional() })).optional(),`,
    );
  }
  if (hasActions) {
    schemaLines.push(
      `    action: ActionSchema.describe('REF:#/$defs/Action|Action dispatched on user interaction.').optional(),`,
    );
  }

  const directProps = props.filter((p) => !(slotType === 'label-child' && p.name === 'label'));
  const attrLines: string[] = [];

  for (const p of directProps) {
    const key = quoteName(p.name);
    if (p.kind === 'dynamicBoolean') {
      attrLines.push(`      .${key}=\${Boolean(p.${key})}`);
    } else if (noUndef.has(p.name) || p.kind === 'enum' || p.kind === 'literal' || p.kind === 'dynamicString' || p.kind === 'dynamicNumber') {
      attrLines.push(`      .${key}=\${ifDefined(p.${key})}`);
    } else {
      attrLines.push(`      .${key}=\${ifDefined(p.${key})}`);
    }
  }

  const usesCustomActionEvent = Boolean(customAction) || (Boolean(twoWay) && twoWay.event === 'page-change');

  if (hasActions && !usesCustomActionEvent) {
    attrLines.push(`      @click=\${this.handleAction}`);
  } else if (customAction && hasActions) {
    attrLines.push(`      @${customAction.event}=\${this.handleAction}`);
  }
  if (twoWay) {
    attrLines.push(`      @${twoWay.event}=\${this.handleTwoWay}`);
  }

  const handlerLines: string[] = [];
  if (hasActions && !usesCustomActionEvent) {
    handlerLines.push(
      '',
      '  private handleAction() {',
      '    void this.controller.props.action?.();',
      '  }',
    );
  } else if (customAction && hasActions) {
    handlerLines.push(
      '',
      '  private handleAction(e: Event) {',
      ...(customAction.beforeDispatch ? [`    ${customAction.beforeDispatch}`] : []),
      '    void this.controller.props.action?.();',
      '  }',
    );
  }

  if (twoWay) {
    handlerLines.push(
      '',
      '  private handleTwoWay(e: Event) {',
      `    const next = ${twoWay.extract};`,
      `    (this.controller.props as unknown as Record<string, ((v: unknown) => void) | undefined>).${twoWay.setter}?.(next);`,
      ...(hasActions ? ['    void this.controller.props.action?.();'] : []),
      '  }',
    );
  }

  let innerHtml = '';
  if (sdui === 'AgTimeline') {
    innerHtml = `\${(p.items ?? []).map((item) => html\`<ag-timeline-item marker-aria-label=\${ifDefined(item.markerAriaLabel)}>\${item.start ? html\`<span slot="ag-start">\${item.start}</span>\` : ''}\${item.marker ? html\`<span slot="ag-marker">\${item.marker}</span>\` : ''}\${item.end ? html\`<span slot="ag-end">\${item.end}</span>\` : ''}</ag-timeline-item>\`)}`;
  } else if (slotType === 'label-child') {
    innerHtml = "${p.children?.length ? p.children.map((c) => this.renderNode(c)) : (p.label ?? '')}";
  } else if (slotType === 'children') {
    innerHtml = '${(p.children ?? []).map((c) => this.renderNode(c))}';
  }

  const openTag = attrLines.length > 0
    ? `    return html\`<${tag}\n${attrLines.join('\n')}\n    >${innerHtml}</${tag}>\`;`
    : `    return html\`<${tag}>${innerHtml}</${tag}>\`;`;

  return [
    GENERATED_HEADER,
    "import { html } from 'lit';",
    "import { ifDefined } from 'lit/directives/if-defined.js';",
    "import { z } from 'zod';",
    `import { ${coreImports.join(', ')} } from '@a2ui/web_core/v1_0';`,
    `import 'agnosticui-core/${slug}';`,
    '',
    `export const ${sdui}Schema = z`,
    '  .object({',
    ...schemaLines,
    '  })',
    '  .strict();',
    '',
    `export const ${sdui}Api = {`,
    `  name: '${sdui}' as const,`,
    `  schema: ${sdui}Schema,`,
    '};',
    '',
    `export class ${elementClass} extends A2uiLitElement<typeof ${sdui}Api> {`,
    `  static readonly tagName = '${wrapperTag}';`,
    '',
    '  override createRenderRoot() {',
    '    return this;',
    '  }',
    ...handlerLines,
    '',
    '  override render() {',
    '    const p = this.controller.props;',
    openTag,
    '  }',
    '}',
    '',
    `export const ${sdui} = {`,
    `  ...${sdui}Api,`,
    `  element: ${elementClass},`,
    `  tagName: ${elementClass}.tagName,`,
    '};',
    '',
  ].join('\n');
}

function generateAgTextFile(): string {
  return [
    GENERATED_HEADER,
    "import { html } from 'lit';",
    "import { z } from 'zod';",
    "import { DynamicStringSchema, A2uiLitElement } from '@a2ui/web_core/v1_0';",
    '',
    'export const AgTextSchema = z',
    '  .object({',
    "    text: DynamicStringSchema.describe('REF:#/\$defs/DynamicString|Text content rendered inside the element.'),",
    '    el: z',
    "      .enum(['p', 'span', 'div', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'label'])",
    "      .describe('Semantic HTML tag to render.')",
    '      .optional(),',
    '  })',
    '  .strict();',
    '',
    'export const AgTextApi = {',
    "  name: 'AgText' as const,",
    '  schema: AgTextSchema,',
    '};',
    '',
    'export class AgA2uiTextElement extends A2uiLitElement<typeof AgTextApi> {',
    "  static readonly tagName = 'ag-a2ui-text';",
    '',
    '  override createRenderRoot() {',
    '    return this;',
    '  }',
    '',
    '  override render() {',
    '    const p = this.controller.props;',
    "    const text = p.text ?? '';",
    '    switch (p.el) {',
    "      case 'h1': return html`<h1>${text}</h1>`;",
    "      case 'h2': return html`<h2>${text}</h2>`;",
    "      case 'h3': return html`<h3>${text}</h3>`;",
    "      case 'h4': return html`<h4>${text}</h4>`;",
    "      case 'h5': return html`<h5>${text}</h5>`;",
    "      case 'h6': return html`<h6>${text}</h6>`;",
    "      case 'span': return html`<span>${text}</span>`;",
    "      case 'div': return html`<div>${text}</div>`;",
    "      case 'label': return html`<label>${text}</label>`;",
    "      default: return html`<p>${text}</p>`;",
    '    }',
    '  }',
    '}',
    '',
    'export const AgText = {',
    '  ...AgTextApi,',
    '  element: AgA2uiTextElement,',
    '  tagName: AgA2uiTextElement.tagName,',
    '};',
    '',
  ].join('\n');
}

